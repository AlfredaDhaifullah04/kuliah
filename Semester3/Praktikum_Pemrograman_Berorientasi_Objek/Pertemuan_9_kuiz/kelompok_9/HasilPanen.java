package kelompok_9;

public class HasilPanen {
    private String nama;
    private int jumlah;

    public HasilPanen(String nama, int jumlah) {
        this.nama = nama;
        this.jumlah = jumlah;
    }

    public String getNama() { 
        return nama; 
    }

    public int getJumlah() { 
        return jumlah; 
    }
}