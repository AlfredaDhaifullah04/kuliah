CREATE TABLE public.m_city (
	city_id serial4 NOT NULL,
	city_name varchar NULL,
	CONSTRAINT m_city_pk PRIMARY KEY (city_id)
);

CREATE TABLE public.m_brand (
	brand_id serial4 NOT NULL,
	brand_name varchar NULL,
	CONSTRAINT m_brand_pk PRIMARY KEY (brand_id),
	CONSTRAINT m_brand_unique UNIQUE (brand_name)
);

CREATE TABLE public.m_category (
	category_id serial4 NOT NULL,
	category_name varchar NULL,
	CONSTRAINT m_kategori_pk PRIMARY KEY (category_id)
);

CREATE TABLE public.m_cashier (
	cashier_id serial4 NOT NULL,
	cashier_name varchar NULL,
	cashier_phone varchar NULL,
	city_id int4 NULL,
	CONSTRAINT m_cashier_pk PRIMARY KEY (cashier_id),
	CONSTRAINT m_cashier_m_city_fk FOREIGN KEY (city_id) REFERENCES public.m_city(city_id)
);

CREATE TABLE public.m_customer (
	customer_id serial4 NOT NULL,
	customer_name varchar NULL,
	customer_phone varchar NULL,
	city_id int4 NULL,
	CONSTRAINT m_customer_pk PRIMARY KEY (customer_id),
	CONSTRAINT m_customer_m_city_fk FOREIGN KEY (city_id) REFERENCES public.m_city(city_id)
);

CREATE TABLE public.m_unit (
	unit_id serial4 NOT NULL,
	unit_name varchar NULL,
	CONSTRAINT m_unit_pk PRIMARY KEY (unit_id)
);

CREATE TABLE public.m_supplier (
	supplier_id serial4 NOT NULL,
	supplier_name varchar NULL,
	supplier_phone varchar NULL,
	city_id int4 NULL,
	CONSTRAINT m_supplier_pk PRIMARY KEY (supplier_id),
	CONSTRAINT m_supplier_m_city_fk FOREIGN KEY (city_id) REFERENCES public.m_city(city_id)
);

CREATE TABLE public.m_product (
	product_id serial4 NOT NULL,
	product_name varchar NULL,
	product_price money NULL,
	purchase_price money NULL,
	category_id int4 NULL,
	unit_id int4 NULL,
	brand_id int4 NULL,
	CONSTRAINT m_product_pk PRIMARY KEY (product_id),
	CONSTRAINT m_product_m_brand_fk FOREIGN KEY (brand_id) REFERENCES public.m_brand(brand_id),
	CONSTRAINT m_product_m_category_fk FOREIGN KEY (category_id) REFERENCES public.m_category(category_id),
	CONSTRAINT m_product_m_unit_fk FOREIGN KEY (unit_id) REFERENCES public.m_unit(unit_id)
);



CREATE TABLE public.t_stockin (
	stockin_id serial4 NOT NULL,
	stockin_date timestamp NULL,
	supplier_id int4 NULL,
	cashier_id int4 NULL,
	CONSTRAINT t_stock_in_pk PRIMARY KEY (stockin_id),
	CONSTRAINT t_stockin_m_cashier_fk FOREIGN KEY (cashier_id) REFERENCES public.m_cashier(cashier_id),
	CONSTRAINT t_stockin_m_supplier_fk FOREIGN KEY (supplier_id) REFERENCES public.m_supplier(supplier_id)
);


CREATE TABLE public.t_sales (
	sales_id serial4 NOT NULL,
	sales_date timestamp NULL,
	customer_id int4 NULL,
	cashier_id int4 NULL,
	payment_type varchar NULL,
	CONSTRAINT t_sales_pk PRIMARY KEY (sales_id),
	CONSTRAINT t_sales_m_cashier_fk FOREIGN KEY (cashier_id) REFERENCES public.m_cashier(cashier_id),
	CONSTRAINT t_sales_m_customer_fk FOREIGN KEY (customer_id) REFERENCES public.m_customer(customer_id)
);

CREATE TABLE public.t_stockin_detail (
	stockin_detail_id serial4 NOT NULL,
	stockin_id int4 NULL,
	product_id int4 NULL,
	quantity int2 NULL,
	CONSTRAINT t_stockin_detail_pk PRIMARY KEY (stockin_detail_id),
	CONSTRAINT t_stockin_detail_m_product_fk FOREIGN KEY (product_id) REFERENCES public.m_product(product_id),
	CONSTRAINT t_stockin_detail_t_stockin_fk FOREIGN KEY (stockin_id) REFERENCES public.t_stockin(stockin_id)
);

CREATE TABLE public.t_sales_detail (
	sales_detail_id serial4 NOT NULL,
	sales_id int4 NULL,
	product_id int4 NULL,
	product_price money NULL,
	product_qty int2 NULL,
	amount money GENERATED ALWAYS AS (product_price * product_qty) STORED NULL,
	CONSTRAINT t_sales_detail_pk PRIMARY KEY (sales_detail_id),
	CONSTRAINT t_sales_detail_m_product_fk FOREIGN KEY (product_id) REFERENCES public.m_product(product_id),
	CONSTRAINT t_sales_detail_t_sales_fk FOREIGN KEY (sales_id) REFERENCES public.t_sales(sales_id)
);

