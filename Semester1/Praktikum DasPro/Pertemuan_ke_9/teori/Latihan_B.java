package Pertemuan_ke_9.teori;

public class Latihan_B {
    public static void main(String[] args) {
        
        int n = 10;
        for (int i = 0; i < n; i++) {
            for (int j = 0; j <= i; ) {                
                    System.out.print("*");
               
                j++;
                
            }
            System.out.println();
        }
    }
}
